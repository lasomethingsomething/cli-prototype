// TestFindModelFileSkipsGeneratedFiles tests that FindModelFile skips files generated by model-cli
func TestFindModelFileSkipsGeneratedFiles(t *testing.T) {
	tmpDir, err := os.MkdirTemp("", "model-format-test-skip")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tmpDir)

	// Create only generated files (no actual model)
	if err := os.WriteFile(filepath.Join(tmpDir, "config.json"), []byte("{}"), 0644); err != nil {
		t.Fatalf("failed to create config.json: %v", err)
	}
	if err := os.WriteFile(filepath.Join(tmpDir, "manifest.json"), []byte("{}"), 0644); err != nil {
		t.Fatalf("failed to create manifest.json: %v", err)
	}
	if err := os.WriteFile(filepath.Join(tmpDir, "sbom.spdx-json"), []byte("{}"), 0644); err != nil {
		t.Fatalf("failed to create sbom.spdx-json: %v", err)
	}
	if err := os.WriteFile(filepath.Join(tmpDir, "mof.json"), []byte("{}"), 0644); err != nil {
		t.Fatalf("failed to create mof.json: %v", err)
	}

	result := FindModelFile(tmpDir)
	if result != "" {
		t.Errorf("FindModelFile returned %q for directory with only generated files, expected empty string", result)
	}
}

// TestDetectModelFormatFromPath tests that DetectModelFormatFromPath correctly identifies model formats
func TestDetectModelFormatFromPath(t *testing.T) {
	tmpDir, err := os.MkdirTemp("", "model-format-detect")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tmpDir)

	// Create a sklearn model directory
	sklDir := filepath.Join(tmpDir, "sklearn")
	if err := os.MkdirAll(sklDir, 0755); err != nil {
		t.Fatalf("failed to create sklearn dir: %v", err)
	}
	if err := os.WriteFile(filepath.Join(sklDir, "model.joblib"), []byte("data"), 0644); err != nil {
		t.Fatalf("failed to create model.joblib: %v", err)
	}

	format := DetectModelFormatFromPath(sklDir)
	if format != ModelFormatSklearn {
		t.Errorf("DetectModelFormatFromPath returned %q for .joblib file, expected %q", format, ModelFormatSklearn)
	}
}
