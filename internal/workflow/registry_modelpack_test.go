// TestModelPackDelegatesManifestOperationsToORAS verifies the read and
// referrer operations run oras, never modctl.
func TestModelPackDelegatesManifestOperationsToORAS(t *testing.T) {
	p := &ModelPackProvider{}
	for _, tc := range []struct {
		name     string
		response string
		op       func() error
		wantArgs []string
	}{
		{
			"GetArtifactDigest", descriptor,
			func() error { _, err := p.GetArtifactDigest("my-model:v1", "ghcr.io/my-org"); return err },
			[]string{"manifest", "fetch", "--descriptor", "ghcr.io/my-org/my-model:v1"},
		},
		{
			"FetchManifestAnnotations", storedManifest,
			func() error { _, err := p.FetchManifestAnnotations("ghcr.io/my-org/my-model:v1"); return err },
			[]string{"manifest", "fetch", "ghcr.io/my-org/my-model:v1"},
		},
		{
			"GetReferrers", `{"referrers":[]}`,
			func() error { _, err := p.GetReferrers("my-model:v1", "ghcr.io/my-org", "t"); return err },
			[]string{"discover", "--artifact-type", "t", "--format", "json", "ghcr.io/my-org/my-model:v1"},
		},
		{
			"PushReferrer", "",
			func() error { return p.PushReferrer("my-model:v1", "ghcr.io/my-org", "t", []byte("{}"), nil) },
			[]string{"attach", "ghcr.io/my-org/my-model:v1", "--artifact-type", "t", "referrer.json:t"},
		},
		{
			"Search", `{"manifests":[]}`,
			func() error { _, err := p.Search("ghcr.io/my-org", NewSearchQuery()); return err },
			[]string{"repo", "ls", "ghcr.io/my-org"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			modctl := installFakeTool(t, "modctl", []string{""}, 0)
			oras := installFakeTool(t, "oras", []string{tc.response}, 0)
			if err := tc.op(); err != nil {
				t.Fatalf("%s() error = %v", tc.name, err)
			}
			if calls := modctl.calls(); len(calls) != 0 {
				t.Errorf("%s() ran modctl: %v", tc.name, calls)
			}
			calls := oras.calls()
			if len(calls) == 0 {
				t.Fatalf("%s() did not run oras", tc.name)
			}
			if got := argv(t, calls[0]); !reflect.DeepEqual(got, tc.wantArgs) {
				t.Errorf("oras args = %v, want %v", got, tc.wantArgs)
			}
		})
	}
}

func TestMergeManifestAnnotations(t *testing.T) {
	t.Run("adds and overwrites", func(t *testing.T) {
		out, err := mergeManifestAnnotations([]byte(`{"schemaVersion":2,"config":{"digest":"sha256:a"},"annotations":{"keep":"1","k":"old"}}`),
			map[string]string{"k": "new", "added": "2"})
		if err != nil {
			t.Fatal(err)
		}
		var got map[string]interface{}
		if err := json.Unmarshal(out, &got); err != nil {
			t.Fatal(err)
		}
		want := map[string]interface{}{
			"schemaVersion": float64(2),
			"config":        map[string]interface{}{"digest": "sha256:a"},
			"annotations":   map[string]interface{}{"keep": "1", "k": "new", "added": "2"},
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("merged = %v, want %v", got, want)
		}
	})
	t.Run("manifest without annotations", func(t *testing.T) {
		for _, raw := range []string{`{"schemaVersion":2}`, `{"schemaVersion":2,"annotations":null}`} {
			out, err := mergeManifestAnnotations([]byte(raw), map[string]string{"k": "v"})
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(out), `"annotations":{"k":"v"}`) {
				t.Errorf("merged %s = %s", raw, out)
			}
		}
	})
	t.Run("invalid manifest", func(t *testing.T) {
		if _, err := mergeManifestAnnotations([]byte("nope"), nil); err == nil {
			t.Error("expected an error for invalid JSON")
		}
	})
}

