// writeModelDir creates a model directory with the given files (relative
// paths, subdirectories allowed) and returns its path.
func writeModelDir(t *testing.T, files ...string) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "my-model")
	for _, f := range files {
		p := filepath.Join(dir, f)
		if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte("content of "+f), 0644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const (
	storedManifest = `{"schemaVersion":2,"mediaType":"application/vnd.oci.image.manifest.v1+json",` +
		`"artifactType":"application/vnd.cncf.model.manifest.v1+json",` +
		`"config":{"mediaType":"application/vnd.cncf.model.config.v1+json","digest":"sha256:aaaa","size":1},` +
		`"layers":[{"mediaType":"application/vnd.cncf.model.weight.v1.raw","digest":"sha256:bbbb","size":2}],` +
		`"annotations":{"org.cncf.modctl.modelfile":"NAME my-model\n"}}`
	descriptor = `{"mediaType":"application/vnd.oci.image.manifest.v1+json","digest":"` + testDigest + `","size":512}`
)

// argv splits a recorded fake-tool call into its arguments.
func argv(t *testing.T, call string) []string {
	t.Helper()
	_, args, _ := strings.Cut(call, "\t")
	return strings.Fields(args)
}

func TestModelPackPushBuildsPushesAndAnnotates(t *testing.T) {
	modctl := installFakeTool(t, "modctl", []string{""}, 0)
	// fetch manifest, push annotated manifest, fetch descriptor
	oras := installFakeTool(t, "oras", []string{storedManifest, "", descriptor}, 0)

	modelDir := writeModelDir(t, "model.safetensors", "config.json", "README.md", "sub/weights.bin", ".hidden/secret")

	digest, err := (&ModelPackProvider{}).Push("my-model:v1", "ghcr.io/my-org", modelDir, map[string]string{
		AnnotationArtifactType: "model",
		AnnotationRuntime:      "vllm",
	})
	if err != nil {
		t.Fatalf("Push() error = %v", err)
	}
	if digest != testDigest {
		t.Errorf("Push() digest = %q, want the annotated manifest's digest %q", digest, testDigest)
	}

	calls := modctl.calls()
	if len(calls) != 2 {
		t.Fatalf("expected modctl build then push, got %d calls: %v", len(calls), calls)
	}
	build := argv(t, calls[0])
	if len(build) != 6 || build[0] != "build" || build[1] != "-t" || build[2] != "ghcr.io/my-org/my-model:v1" ||
		build[3] != "-f" || filepath.Base(build[4]) != "Modelfile" || build[5] != modelDir {
		t.Errorf("modctl build args = %v, want build -t ghcr.io/my-org/my-model:v1 -f <tmp>/Modelfile %s", build, modelDir)
	}
	if len(build) == 6 && strings.HasPrefix(build[4], modelDir) {
		t.Errorf("generated Modelfile %s was written into the model directory", build[4])
	}
	wantModelfile := "# Generated by model-cli for modctl build\n" +
		"NAME my-model\n" +
		"DOC README.md\n" +
		"CONFIG config.json\n" +
		"MODEL model.safetensors\n" +
		"MODEL sub/weights.bin\n"
	if got := string(modctl.file(t, 0, "Modelfile")); got != wantModelfile {
		t.Errorf("Modelfile =\n%s\nwant\n%s", got, wantModelfile)
	}
	if push := argv(t, calls[1]); !reflect.DeepEqual(push, []string{"push", "ghcr.io/my-org/my-model:v1"}) {
		t.Errorf("modctl push args = %v", push)
	}

	orasCalls := oras.calls()
	if len(orasCalls) != 3 {
		t.Fatalf("expected oras manifest fetch, manifest push, descriptor fetch; got %d calls: %v", len(orasCalls), orasCalls)
	}
	if got := argv(t, orasCalls[0]); !reflect.DeepEqual(got, []string{"manifest", "fetch", "ghcr.io/my-org/my-model:v1"}) {
		t.Errorf("oras call 0 = %v, want manifest fetch", got)
	}
	if got := argv(t, orasCalls[1]); len(got) != 4 || got[0] != "manifest" || got[1] != "push" ||
		got[2] != "ghcr.io/my-org/my-model:v1" || filepath.Base(got[3]) != "manifest.json" {
		t.Errorf("oras call 1 = %v, want manifest push ghcr.io/my-org/my-model:v1 <tmp>/manifest.json", got)
	}
	if got := argv(t, orasCalls[2]); !reflect.DeepEqual(got, []string{"manifest", "fetch", "--descriptor", "ghcr.io/my-org/my-model:v1"}) {
		t.Errorf("oras call 2 = %v, want descriptor fetch", got)
	}

	// The re-pushed manifest is the stored one plus the CNCF annotations.
	var pushed struct {
		SchemaVersion int               `json:"schemaVersion"`
		MediaType     string            `json:"mediaType"`
		ArtifactType  string            `json:"artifactType"`
		Layers        []json.RawMessage `json:"layers"`
		Annotations   map[string]string `json:"annotations"`
	}
	if err := json.Unmarshal(oras.file(t, 1, "manifest.json"), &pushed); err != nil {
		t.Fatalf("pushed manifest is not JSON: %v", err)
	}
	if pushed.SchemaVersion != 2 || pushed.MediaType != "application/vnd.oci.image.manifest.v1+json" ||
		pushed.ArtifactType != "application/vnd.cncf.model.manifest.v1+json" || len(pushed.Layers) != 1 {
		t.Errorf("pushed manifest lost fields: %+v", pushed)
	}
	wantAnnotations := map[string]string{
		"org.cncf.modctl.modelfile": "NAME my-model\n",
		AnnotationArtifactType:      "model",
		AnnotationRuntime:           "vllm",
	}
	if !reflect.DeepEqual(pushed.Annotations, wantAnnotations) {
		t.Errorf("pushed annotations = %v, want %v", pushed.Annotations, wantAnnotations)
	}
}

